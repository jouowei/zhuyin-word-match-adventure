import { Lesson } from '../types';

/**
 * Short texts written for this app (not from any textbook), for 練習課文 when a family hasn't typed its own.
 * Length and words grow with the school term, the way the readers do:
 * - 一上: 30–40 characters, repeated patterns, after the zhuyin weeks
 * - 一下: 40–70 characters, a little story
 * - 二上: about 90 characters, with dialogue
 * - 二下: 100–125 characters, places in Taiwan and feelings
 *
 * Pages are split with ===. In the text, a character with several readings is either inside a vocabulary word
 * (its reading comes from 萌典 for that word) or read the common way, which the font shows by default;
 * tests/lesson-library.test.ts checks this.
 */
const lesson = (
  id: string, grade: number, term: 'up' | 'down', order: number, title: string, pages: string[], vocabulary: string[],
  zhuyinOverrides?: Record<string, string>,
): Lesson => ({ id: `lib-${id}`, grade, term, order, title, content: pages.join('===\n'), vocabulary, ...(zhuyinOverrides && { zhuyinOverrides }) });

